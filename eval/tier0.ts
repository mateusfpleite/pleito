/**
 * Tier 0 Gate — STRUCTURAL containment (SPEC §11a, §5 #2).
 *
 * Property-based, deterministic, zero cost: NO LLM, NO corpus comparison.
 * The invariants generalize to never-seen editais because they are
 * properties of the confrontation between structured fields:
 *
 *   - `afirmacaoVigencia` (Drafter decision per cited lei, §5 #2)
 *   - `statusVerificado` (Norma Verifier verdict per referenced lei)
 *   - `matchNorma` (deterministic status from the curated baseline)
 *
 * CONTAINMENT IS STRUCTURAL: the external document contains NO free LLM
 * prose. The Drafter model does not write text — it only emits structured
 * selections of findings already present in the extraction; the ofício body
 * is assembled 100% by deterministic adapter TEMPLATES. The guarantee is
 * the ABSENCE of free prose, not any regex. This Tier 0 is a redundant HARD
 * GATE (defense-in-depth): any violation = build fails.
 *
 * The lexical scan (check 2) is a DEFENSIVE TRIPWIRE, NOT the containment
 * mechanism: if it fires, it is a structural bug (a template introduced
 * status prose without verified backing) — it should never fire.
 *
 * 4 checks (SPEC §11a):
 *   1. afirmacao-indevida / afirmacao-vigencia-proativa — structural
 *      confrontation afirmacaoVigencia × statusVerificado (no regex in the
 *      primary gate).
 *   2. lexico-inconsistente — defensive TRIPWIRE (not the guarantee):
 *      revocation prose in the markdown without verified structured backing
 *      = structural bug.
 *   3. baseline-divergente — a VERIFIED statusVerificado diverges from the
 *      curated baseline's deterministic category.
 *   4. zona-cinzenta-binarizada — a zona-cinzenta lei must never become a
 *      binary assertion (revogada/vigente) in the ofício.
 */

import type { EditalExtraction } from '../domain/schema.ts';
import type { OficioGerado } from '../domain/ports.ts';
import { matchNorma } from '../domain/norma-baseline.ts';
import { categoriaParaStatus } from '../domain/categoria-status.ts';

type StatusVerificado =
  EditalExtraction['leisReferenciadas'][number]['statusVerificado'];

/** A gate violation. `tipo` is categorical; `detalhe` is diagnostic. */
export type Violacao = {
  tipo:
    | 'afirmacao-indevida'
    | 'afirmacao-vigencia-proativa'
    | 'lexico-inconsistente'
    | 'baseline-divergente'
    | 'zona-cinzenta-binarizada';
  detalhe: string;
};

/**
 * Gate input: what the Phase 10 workflow produces per analysis — the final
 * extraction (with `statusVerificado` filled in by the Norma Verifier) and
 * the ofício generated by the Drafter (or `null` when gate B did not fire).
 */
export type AnaliseParaGate = {
  extracao: EditalExtraction;
  oficio: OficioGerado | null;
};

/**
 * Lexical (non-)validity TRIPWIRE — identical to the Drafter's internal
 * tripwire (SPEC §5 #2 / §11a). It is NOT the containment mechanism
 * (containment is the absence of free model prose); it is defense-in-depth
 * that should NEVER fire. Expanded for paraphrases that leaked in
 * production (ab-rogad, derrogad, não subsiste, exaurid, etc.).
 */
const LEXICO_VIGENCIA =
  /revogad|ab-?rogad|derrogad|revogou-se|perdeu vig[êe]ncia|n[ãa]o subsiste|superad|exaurid|deixou de produzir efeitos|n[ãa]o vige|sem efic[áa]cia|n[ãa]o est[áa] (mais )?em vigor|deixou de viger|sem vig[êe]ncia|caducou/i;

/**
 * Curated baseline category → expected `statusVerificado`. Delegates to the
 * SINGLE CANONICAL map `domain/categoria-status.ts` (the SAME source as the
 * Norma Verifier — a safety mapping, no divergeable copy). Unknown category
 * → null (no deterministic expectation → does not flag divergence).
 */
function categoriaParaStatusEsperado(
  categoria: string
): StatusVerificado | null {
  return categoriaParaStatus(categoria);
}

/** Short textual reference for a lei (for `detalhe`). */
function ref(numero: string | null, ano: number | null): string {
  return `${numero ?? '?'}/${ano ?? '?'}`;
}

/**
 * ROBUST lookup of a cited lei against `leisReferenciadas` (mirrors the
 * Drafter's C2 rule): `numero|ano` null OR non-unique key → not
 * identifiable (never safely assigns a status). Only a UNIQUE match returns
 * the `statusVerificado`.
 */
function lookupStatus(
  extracao: EditalExtraction,
  numero: string | null,
  ano: number | null
): { identificavel: boolean; statusVerificado: StatusVerificado | null } {
  if (numero === null || ano === null) {
    return { identificavel: false, statusVerificado: null };
  }
  const matches = extracao.leisReferenciadas.filter(
    (r) => r.numero === numero && r.ano === ano
  );
  if (matches.length !== 1) {
    return { identificavel: false, statusVerificado: null };
  }
  return {
    identificavel: true,
    statusVerificado: matches[0].statusVerificado,
  };
}

/**
 * CHECK 1 — STRUCTURAL primary gate (no regex). For each cited lei:
 *  - `afirmacaoVigencia==='vigente'` → ALWAYS a violation: the Drafter must
 *    never assert validity proactively (SPEC §5 #2: only `nenhuma` or
 *    `revogada`).
 *  - `afirmacaoVigencia==='revogada'` → requires the corresponding lei in
 *    `leisReferenciadas` (robust lookup) with `statusVerificado==='revogada'`.
 *    A non-identifiable/ambiguous lei, or status ≠ revogada → violation.
 */
function checarGatePrimario(analise: AnaliseParaGate): Violacao[] {
  const { extracao, oficio } = analise;
  if (!oficio) return [];
  const violacoes: Violacao[] = [];

  for (const lei of oficio.leisCitadas) {
    if (lei.afirmacaoVigencia === 'vigente') {
      violacoes.push({
        tipo: 'afirmacao-vigencia-proativa',
        detalhe:
          `Lei ${ref(lei.numero, lei.ano)} com afirmacaoVigencia='vigente' ` +
          `— o Drafter nunca deve afirmar vigência proativamente (§5 #2: ` +
          `só 'nenhuma' ou 'revogada').`,
      });
      continue;
    }

    if (lei.afirmacaoVigencia === 'revogada') {
      const lk = lookupStatus(extracao, lei.numero, lei.ano);
      if (!lk.identificavel) {
        violacoes.push({
          tipo: 'afirmacao-indevida',
          detalhe:
            `Lei ${ref(lei.numero, lei.ano)} afirmada 'revogada' mas NÃO ` +
            `é identificável de forma única em leisReferenciadas ` +
            `(numero/ano null ou chave ambígua) — afirmação de revogação ` +
            `sobre lei não-identificável é indevida.`,
        });
        continue;
      }
      if (lk.statusVerificado !== 'revogada') {
        violacoes.push({
          tipo: 'afirmacao-indevida',
          detalhe:
            `Lei ${ref(lei.numero, lei.ano)} afirmada 'revogada' no ofício ` +
            `mas statusVerificado='${lk.statusVerificado}' na extração ` +
            `(exigido 'revogada').`,
        });
      }
    }
  }

  return violacoes;
}

/**
 * CHECK 2 — DEFENSIVE TRIPWIRE (not the containment mechanism). Since the
 * ofício body is 100% templated and the only permitted revocation lexicon
 * comes from the revocation template (only under a verified revoked lei),
 * if the markdown matches the lexicon BUT no `leisCitadas` entry has
 * `afirmacaoVigencia==='revogada'` with `statusVerificado='revogada'`
 * backing it → STRUCTURAL BUG (a template introduced improper status
 * prose). It should never fire — the guarantee is the absence of free
 * prose, not this scan.
 */
function checarBackstopLexico(analise: AnaliseParaGate): Violacao[] {
  const { extracao, oficio } = analise;
  if (!oficio) return [];
  if (!LEXICO_VIGENCIA.test(oficio.markdown)) return [];

  const temRespaldo = oficio.leisCitadas.some((lei) => {
    if (lei.afirmacaoVigencia !== 'revogada') return false;
    const lk = lookupStatus(extracao, lei.numero, lei.ano);
    return lk.identificavel && lk.statusVerificado === 'revogada';
  });

  if (temRespaldo) return [];

  return [
    {
      tipo: 'lexico-inconsistente',
      detalhe:
        'Markdown do ofício casa léxico de revogação mas NENHUMA lei ' +
        "citada tem afirmacaoVigencia='revogada' com statusVerificado=" +
        "'revogada' que respalde a prosa — inconsistência estrutural.",
    },
  ];
}

/**
 * CHECK 3 — baseline consistency. For each lei in `leisReferenciadas`: if
 * `matchNorma` classifies it into a deterministic-status category and the
 * (ALREADY VERIFIED) `statusVerificado` diverges from what the category
 * expects → divergence. `nao-verificado` is NOT a divergence (raw/gold
 * extractions have not gone through the Verifier yet).
 */
function checarBaseline(analise: AnaliseParaGate): Violacao[] {
  const { extracao } = analise;
  const violacoes: Violacao[] = [];

  for (const lei of extracao.leisReferenciadas) {
    if (lei.statusVerificado === 'nao-verificado') continue;

    const hit = matchNorma({
      numero: lei.numero,
      ano: lei.ano,
      escopo: lei.escopo,
      tipoNorma: lei.tipoNorma,
    });
    if (!hit) continue;

    const esperado = categoriaParaStatusEsperado(hit.categoria);
    if (esperado === null) continue;

    if (lei.statusVerificado !== esperado) {
      violacoes.push({
        tipo: 'baseline-divergente',
        detalhe:
          `Lei ${ref(lei.numero, lei.ano)} casa baseline ` +
          `'${hit.entry.id}' (categoria '${hit.categoria}', via ` +
          `'${hit.via}') → esperado statusVerificado='${esperado}', ` +
          `obtido '${lei.statusVerificado}'.`,
      });
    }
  }

  return violacoes;
}

/**
 * CHECK 4 — zona-cinzenta never becomes binary. A lei whose `matchNorma`
 * resolves to `zona-cinzenta` with `afirmacaoVigencia ∈ {revogada,vigente}`
 * in the ofício → violation (binary status over a legally disputed norm).
 */
function checarZonaCinzenta(analise: AnaliseParaGate): Violacao[] {
  const { extracao, oficio } = analise;
  if (!oficio) return [];
  const violacoes: Violacao[] = [];

  // Index: numero|ano → referenced leis (to reconstruct escopo/tipo).
  for (const lei of oficio.leisCitadas) {
    if (lei.afirmacaoVigencia === 'nenhuma') continue;
    if (lei.numero === null || lei.ano === null) continue;

    const refs = extracao.leisReferenciadas.filter(
      (r) => r.numero === lei.numero && r.ano === lei.ano
    );
    const escopo = refs[0]?.escopo ?? 'federal';
    const tipoNorma = refs[0]?.tipoNorma ?? null;

    const hit = matchNorma({
      numero: lei.numero,
      ano: lei.ano,
      escopo,
      tipoNorma,
    });
    if (hit?.categoria === 'zona-cinzenta') {
      violacoes.push({
        tipo: 'zona-cinzenta-binarizada',
        detalhe:
          `Lei ${ref(lei.numero, lei.ano)} casa baseline ` +
          `'${hit.entry.id}' (zona-cinzenta) mas o ofício afirma ` +
          `afirmacaoVigencia='${lei.afirmacaoVigencia}' — status ` +
          `binário sobre norma juridicamente disputada é proibido.`,
      });
    }
  }

  return violacoes;
}

/**
 * TIER 0 GATE. Runs the 4 structural checks. `oficio:null` is valid (gate B
 * did not fire) — only the checks that depend on the ofício are skipped;
 * baseline consistency (check 3) still runs over the extraction.
 *
 * Deterministic, no side effects, no I/O, no LLM.
 */
export function checarContencao(analise: AnaliseParaGate): {
  violacoes: Violacao[];
} {
  return {
    violacoes: [
      ...checarGatePrimario(analise),
      ...checarBackstopLexico(analise),
      ...checarBaseline(analise),
      ...checarZonaCinzenta(analise),
    ],
  };
}
